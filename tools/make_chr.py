# Boss: a red wyrm, drawn procedurally then auto-outlined.
def draw_wyrm(wing_drop):
    W = 32
    g = [[0] * W for _ in range(W)]

    def ellipse(cx, cy, rx, ry, c):
        for y in range(W):
            for x in range(W):
                if ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1.0:
                    g[y][x] = c

    def poly(pts, c):
        n = len(pts)
        for y in range(W):
            for x in range(W):
                px, py = x + 0.5, y + 0.5
                inside = False
                j = n - 1
                for i in range(n):
                    xi, yi = pts[i]
                    xj, yj = pts[j]
                    if (yi > py) != (yj > py) and px < (xj - xi) * (py - yi) / (yj - yi) + xi:
                        inside = not inside
                    j = i
                if inside:
                    g[y][x] = c

    d = wing_drop
    wing = [(15, 12), (1, 2 + d), (2, 10 + d), (4, 9 + d), (4, 15 + d), (7, 13 + d), (8, 19 + d), (14, 18)]
    poly(wing, 2)
    poly([(31 - x, y) for x, y in wing], 2)
    # wing bones
    for t in range(0, 14):
        x = 15 - t
        y = int(12 + (2 + d - 12) * t / 14)
        g[y][x] = 1
        g[y][31 - x] = 1
    ellipse(15.5, 21, 7, 8.5, 2)
    ellipse(15.5, 23, 4, 6, 3)
    for y in range(18, 30, 3):
        for x in range(12, 20):
            if g[y][x] == 3:
                g[y][x] = 2
    ellipse(15.5, 8, 6, 5, 2)
    poly([(10, 6), (8, 0), (12, 4)], 3)
    poly([(21, 6), (23, 0), (19, 4)], 3)
    ellipse(15.5, 12, 3.5, 2.2, 2)
    # eyes and nostrils
    for (x, y, c) in [(12, 7, 3), (13, 7, 3), (12, 8, 1), (19, 7, 3), (18, 7, 3), (19, 8, 1),
                      (14, 12, 1), (17, 12, 1)]:
        g[y][x] = c
    ellipse(10.5, 29.5, 3, 2, 2)
    ellipse(20.5, 29.5, 3, 2, 2)
    # outline pass
    out = [row[:] for row in g]
    for y in range(W):
        for x in range(W):
            if g[y][x] == 0:
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    X, Y = x + dx, y + dy
                    if 0 <= X < W and 0 <= Y < W and g[Y][X] not in (0, 1):
                        out[y][x] = 1
                        break
    return out


