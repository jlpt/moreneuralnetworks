# ---------------------------------------------------------------- helpers
def norm(rows, w, h):
    """Pad/crop art rows to exactly w x h and convert to ints."""
    out = []
    for r in list(rows)[:h]:
        r = (r + "." * w)[:w]
        out.append([0 if c in ". " else int(c) for c in r])
    while len(out) < h:
        out.append([0] * w)
    return out


def split(px, w, h):
    """Split a w x h pixel grid into 8x8 tiles, row-major."""
    tiles = []
    for ty in range(0, h, 8):
        for tx in range(0, w, 8):
            tiles.append([row[tx:tx + 8] for row in px[ty:ty + 8]])
    return tiles


def encode(tile):
    lo, hi = [], []
    for row in tile:
        a = b = 0
        for x, c in enumerate(row):
            if c & 1:
                a |= 0x80 >> x
            if c & 2:
                b |= 0x80 >> x
        lo.append(a)
        hi.append(b)
    return bytes(lo + hi)


def vflip(px):
    return [list(r) for r in reversed(px)]


def hflip(px):
    return [list(reversed(r)) for r in px]


class Table:
    def __init__(self, name):
        self.name = name
        self.tiles = [[[0] * 8 for _ in range(8)] for _ in range(256)]
        self.next = 0
        self.ids = {}

    def at(self, idx):
        self.next = idx

    def add(self, name, px, w=8, h=8):
        idx = self.next
        for t in split(px, w, h):
            if self.next > 255:
                sys.exit("pattern table %s overflow at %s" % (self.name, name))
            self.tiles[self.next] = t
            self.next += 1
        if name:
            self.ids[name] = idx
        return idx

    def data(self):
        return b"".join(encode(t) for t in self.tiles)


