def forest_version(rows):
    """Tree drawn on dark forest floor: flood the outside green (1) to dark (2)."""
    g = [list(r) for r in rows]
    stack = [(0, 0), (15, 0), (0, 15), (15, 15), (0, 13), (15, 13)]
    while stack:
        x, y = stack.pop()
        if 0 <= x < 16 and 0 <= y < 16 and g[y][x] == "1":
            g[y][x] = "2"
            stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    return ["".join(r) for r in g]


